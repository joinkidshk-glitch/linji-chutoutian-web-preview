# Weave Phase 4-10（v20a33）靜態測試：結局系統——判定純函數／C17 覆寫／前夕相鄰選項／呈現組裝／手帳總結／慣例不變
# 用法：python3 tests/test_weave410_static.py [path-to-index.html]
import sys, pathlib, re
p = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else pathlib.Path(__file__).resolve().parent.parent / 'index.html'
html = p.read_text(encoding='utf-8')
fails = []
def ok(name, cond):
    print(('PASS' if cond else 'FAIL') + ' ' + name)
    if not cond:
        fails.append(name)

def block(decl, endmark):
    i = html.find(decl)
    if i < 0: return ''
    j = html.find(endmark, i)
    return html[i:j] if j > i else ''

blk = block('/* ===== Weave Phase 4-10（v20a33）', 'function pickNpcLine')
ok('phase410 block extractable', bool(blk) and 'resolveEnding410' in blk)

# ---- 判定層 ----
ok('resolveEnding410 defined', 'function resolveEnding410(st, opts)' in blk)
ok('判定唔依賴軌跡分類（resolve 函數體內冇 trajectoryOf49）',
   'trajectoryOf49' not in block('function resolveEnding410(st, opts)', '/* 前夕抉擇選項生成'))
ok('E6 只認 opts.quit 主動入口', 'opts.quit' in block('function resolveEnding410(st, opts)', '/* 前夕抉擇選項生成'))
for frag in ['e1Fame: 60', 'e1Credit: 55', 'e1Dual: 125', 'e4Fame: 50', 'e4CreditBelow: 30',
             'e4RescueCredits: 2', 'e2Credit: 42', 'e2Fame: 35', 'e3Credit: 42',
             'e5FavorTotal: 6', 'e5AgentRel: 60', 'almostRelMin: 4']:
    ok('threshold per design: '+frag, frag in blk)
ok('負標籤清單（專檔：耍大牌／八卦／爛片類＋實際高冷；v20a57 標籤改名）', 'const ENDING_NEG_TAGS410 = ["八卦", "耍大牌", "高冷", "爛片"]' in blk)
ok('E4 兩版 variant（rescued/sunk）', '"rescued"' in blk and '"sunk"' in blk)
ok('半線 commit 定性處理（romance 只認 hiu/choi committed）',
   'rom.hiu.committed' in blk and 'rom.choi.committed' in blk)

# ---- C17 覆寫 ----
node = block('const STORY_SPINE_NODE_C17_410 = {', 'function applyStorySpineOverrides410')
ok('C17 override node defined', bool(node))
for frag in ['title: "三年收科"', 'locId: "tvb_longmen"', 'playerOffer:', 'flag_ending410_natural', 'flag_ending410_quit_job']:
    ok('C17 override fragment: '+frag, frag in node)
ok('C17 override free of old ten-ending ids', all(x not in node for x in ['C17_e01', 'ending_e01', 'endings_catalog', 'E01']))
ok('applyStorySpineOverrides410 defined + wired in refreshCopyPacksFromDisk',
   'function applyStorySpineOverrides410()' in blk and 'applyStorySpineOverrides410();' in html)
ok('C17 SOFT tables aligned', 'C17: "tvb_longmen",' in html and 'C17: "三年收科",' in html and 'C17: { playerHint: "頒獎禮前夕' in html)
gm = re.search(r'const STORY_GATE_3Y = \{(.*?)\n\};', html, re.S)
gate = gm.group(1) if gm else ''
ok('C17 gate unchanged (needDone C13 + yearEq 1990 + 冬)', 'C17: { needDone: ["C13"], yearEq: 1990, seasonIn: ["冬"] }' in gate)

# ---- hooks ----
ok('StoryPlay.start C17 eve-node hook', 'node.id==="C17" && typeof ending410EveNode==="function"' in html)
ok('pickChoice C17 assembly hook', 'ending410AfterEveChoice(n, choice, result)' in html)
ok('eve node builder defined', 'function ending410EveNode(baseNode)' in blk)
ok('eve choices generated by endingEveOptions410 (not hardcoded in node)',
   'endingEveOptions410(S, base)' in block('function ending410EveNode(baseNode)', 'function endingEsc410'))

# ---- 相鄰規則 ----
opts_blk = block('function endingEveOptions410(st, baseRes)', '/* ===== C17 覆寫')
for key in ['"natural"', '"quit_job"', '"quit_leave"', '"to_backstage"', '"to_support"', '"leave_follow"']:
    ok('eve option key present: '+key, ('key: '+key) in opts_blk)
ok('E4->E3 gated by credits<2 + backstage-close', 'favor.creditsHeld<ENDING410_T.e4RescueCredits && endingBackstageClose410(s)' in opts_blk)
ok('leave_follow gated to E0/E2', 'base.career==="E0" || base.career==="E2"' in opts_blk)
ok('quit options carry explicit consequence wording', '唔再係呢行嘅人' in opts_blk and '唔再返呢行' in opts_blk)

# ---- 呈現組裝 ----
for fn in ['function endingCareerScene410', 'function endingRomanceScene410', 'function endingExodusScene410',
           'function endingInserts410', 'function endingSummaryHtml410', 'function showEndingSummary410',
           'function ending410AfterEveChoice']:
    ok('presentation fn: '+fn, fn in blk)
