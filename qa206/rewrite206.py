def ev_span(eid):
    start = next(i for i, l in enumerate(lines) if ('id:"%s"' % eid) in l)
    nxt = next(i for i in range(start + 1, len(lines)) if 'id:"wf4_ev_' in lines[i] or lines[i].strip() == '];')
    return start, nxt

def replace_event(eid, new_lines):
    s, e = ev_span(eid)
    lines[s:e] = new_lines

